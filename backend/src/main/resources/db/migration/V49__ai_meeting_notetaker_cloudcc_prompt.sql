技能名称：客户拜访会议纪要及后续行动管理
目标：将客户拜访的语音对话自动转写为文字，生成标准化会议纪要，并根据对话内容生成待办任务和CRM记录建议，辅助业务人员高效跟进。
触发场景：
- 业务人员要求转写客户拜访录音
- 用户请求生成会议纪要
- 需要从会议内容创建待办任务
- 希望识别会议中的销售线索或商机
处理步骤：
1. 获取语音输入（实时流或录音文件）
2. 进行说话人分离和语音转文本
3. 基于转写文本套用固定模板生成结构化会议纪要
4. 提取行动项生成待办建议，由用户确认是否创建、设定截止时间和被分配人
5. 将确认的待办事项写回业务系统
6. 分析对话内容，识别新销售线索、商机、联系人等，给出创建建议并待用户确认后写入CRM
